<?php

/*
 * 消耗品の年額計算に使う数値パラメータ。
 * 表示用に Blade へ文字列で散っていた値（バッテリー「2〜3年」・プラグ「3,000〜5,000km」）を、
 * 計算に使える数値としてここに一元化する。ConsumableCost がこれを参照する。
 * ★マジックナンバーを裸で置かず、各値の根拠をコメントで残すこと。
 */
return [
    /*
     * 年間走行距離の既定値と選択肢（プラグなど走行距離依存の消耗品の算定に使う）。
     * 3,000km の根拠: 日本自動車工業会「2025年度 二輪車市場動向調査」で国産車全体の
     * 月間走行距離は 229km（年換算 約2,750km）。実勢に寄せ、やや保守的に 3,000km へ丸めた既定値。
     */
    'default_annual_km' => 3000,
    'annual_km_options' => [1000, 3000, 5000, 10000],

    'battery' => [
        /*
         * VRLA（制御弁式鉛蓄電池）バイクバッテリーの実用寿命。
         * 表示は「2〜3年」だが、計算には中央値相当の 3 年を使う（下限2年で割ると年額が過大に出るため、
         * 実勢に近い上限側の3年を採用）。バッテリーは走行距離に依存しない（年数のみ）。
         */
        'life_years' => 3,
    ],

    'plug' => [
        /*
         * スパークプラグの交換サイクル(km)。標準プラグ=5,000km、イリジウム/白金系ロングライフ=15,000km。
         * NGK/DENSO の一般的な推奨値（車種個別値ではなく目安）。表示の「3,000〜5,000km」の上限相当。
         */
        'interval_km' => [
            'standard' => 5000,
            'long_life' => 15000,
        ],
        /*
         * 品番にこれらの文字列を含むものをロングライフ（イリジウム/白金系）とみなす。
         * NGK: IX(イリジウムIX)/RX(ルテニウムHX後継RX)/DX(白金)/IA、DENSO/接頭 SIL・SIM・LMAR はイリジウム系。
         * 判定を config に置くのは、後から品番パターンを追加・修正できるようにするため（コード変更なしで運用調整可能）。
         * 判定は大文字化した品番に対する部分一致。
         */
        'long_life_markers' => ['IX', 'DX', 'RX', 'IA', 'SIL', 'SIM', 'LMAR'],
    ],
];

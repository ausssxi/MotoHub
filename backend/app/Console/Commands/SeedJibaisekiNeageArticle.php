## なぜ上がるのか

損害保険料率算出機構の説明では、主な要因は2つです。

- 物価や賃金の上昇による社費・代理店手数料の増加
- 滞留資金の減少に対応した純保険料率の引き上げ

自賠責保険は「ノーロス・ノープロフィット原則」といって、保険会社が利益も損失も出さないように料率が決められる仕組みです。今回の改定もその調整にあたります。

---

## 自賠責だけでは足りません

最後に、混同しやすい点に触れておきます。

**自賠責保険（強制保険）が補償するのは対人賠償だけで、しかも上限があります。** 相手の車やガードレールを壊した場合の物損、自分のケガ、上限を超える対人賠償は、いずれも対象外です。

事故の賠償は高額になりうるため、対人・対物を無制限にできる任意保険での上乗せが実務的には重要になります。任意保険は自賠責と違って全国一律ではなく、年齢・等級・排気量・補償内容で決まります。

→ **[バイクの保険と維持費](/hoken)** で、任意保険の相場（年齢・等級別）と、排気量別の固定費早見表をまとめています。


<?php

declare(strict_types=1);

namespace App\Console\Commands;

use App\Models\BlogPost;
use App\Models\BlogTag;
use App\Models\User;
use Illuminate\Console\Command;
use Illuminate\Support\Carbon;

/**
 * 「2026年11月1日 自賠責値上げ」記事を投入する（人が確定した原稿・数値は一次資料確定）。
 *
 *  - slug で冪等（再実行しても重複作成しない）。新規は status=published で即公開（編集部の明示指示）。
 *    既存があれば本文・メタのみ更新し status/published_at は維持する。
 *  - ★数値は一次資料（損害保険料率算出機構 2026-04-30 届出）で確定済み。他ソースで上書きしないこと。
 *    Web上に原付12ヶ月=7,800円の誤情報が複数あるが、正しくは 7,730円。
 *  - タグは既存のみ添付（新規タグは作らない）。存在しないタグは警告して skip。
 *  - author_id は本番ユーザーを動的解決（--author=<id|email> 指定可・未指定は is_admin 最若番）。
 */
final class SeedJibaisekiNeageArticle extends Command
{
    protected $signature = 'blog:seed-jibaiseki-neage
        {--author= : 著者ユーザーの id または email（未指定なら is_admin の最若番）}
        {--date= : 公開日 YYYY-MM-DD（未指定なら現在時刻。新規作成時のみ有効）}
        {--unpublish : 記事を下書きに戻して即座に非公開化する（DBには残す＝復元可能。再実行で再公開）}';

    protected $description = '「2026年11月 自賠責値上げ」記事を published で投入する（slug冪等・数値は一次資料確定・既存タグのみ）';

    private const SLUG = 'jibaiseki-neage-2026-11';

    private const TITLE = '【2026年11月1日】バイクの自賠責保険料が値上げ｜排気量別の新料金と、10月までにできること';

    private const META_DESCRIPTION = '2026年11月1日から自賠責保険料が改定。原付は約12%（12ヶ月6,910円→7,730円）、軽二輪・小型二輪は約8〜10%上がります。排気量別・契約期間別の新旧料金を一覧化し、10月31日までにできることも解説します。';

    /** @var list<string> 添付するタグ（既存のみ・新規作成しない）。 */
    private const TAGS = ['自賠責保険', 'バイク保険', '維持費', '法改正・制度'];

    public function handle(): int
    {
        if ($this->option('unpublish')) {
            return $this->unpublish();
        }

        $author = $this->resolveAuthor();
        if ($author === null) {
            $this->error('著者ユーザーを解決できませんでした。--author=<id|email> を指定してください。');

            return self::FAILURE;
        }

        $existing = BlogPost::where('slug', self::SLUG)->first();

        $post = $existing ?? new BlogPost(['slug' => self::SLUG]);
        $post->title = self::TITLE;
        $post->body = $this->body();
        $post->meta_description = self::META_DESCRIPTION;

        if ($existing === null) {
            // 新規は即公開（編集部の明示指示）。
            $post->author_id = $author->id;
            $post->status = 'published';
            $post->published_at = $this->publishedAt();
        }
        // 既存は status / published_at / author を維持（本文・メタのみ更新）。

        $post->save();

        $attached = $this->attachExistingTags($post);

        $this->info(($existing ? '更新しました' : 'published で作成しました')
            .": id={$post->id} slug={$post->slug} status={$post->status}");
        $this->table(['項目', '値'], [
            ['タイトル', $post->title],
            ['URL', url('/blog/'.$post->slug)],
            ['公開日時', (string) $post->published_at],
            ['著者', "id={$author->id} ({$author->email})"],
            ['読了時間', $post->reading_time_minutes.'分'],
            ['添付タグ', $attached === [] ? '(なし)' : implode(' / ', $attached)],
        ]);

        $this->newLine();
        $this->line('次の手順:');
        $this->line('  1. https://motohub.jp/blog/'.self::SLUG.' を確認');
        $this->line('  2. ./deploy-blog.sh（ビルド＋Cloudflare purge）で本番エッジへ反映');

        return self::SUCCESS;
    }

    /**
     * 記事を下書きに戻して即時非公開化する（ソフト削除ではなくDBに残す＝再実行で復元）。
     * 表崩れ等が出たときに素早く引っ込めるための緊急手順。
     */
    private function unpublish(): int
    {
        $post = BlogPost::where('slug', self::SLUG)->first();
        if ($post === null) {
            $this->warn('対象記事が見つかりません（未投入）。何もしていません。');

            return self::SUCCESS;
        }

        $post->status = 'draft';
        $post->published_at = null;
        $post->save();

        $this->info("非公開化しました（下書きに戻しました）: id={$post->id} slug={$post->slug} status={$post->status}");
        $this->line('公開URLは即座に404になります（本文・タグはDBに残るため、再実行で再公開できます）。');
        $this->newLine();
        $this->line('エッジキャッシュも消すには:');
        $this->line('  php artisan blog:purge-cache --url='.url('/blog/'.self::SLUG).' --url='.url('/blog'));

        return self::SUCCESS;
    }

    private function resolveAuthor(): ?User
    {
        $opt = trim((string) $this->option('author'));
        if ($opt !== '') {
            $user = ctype_digit($opt)
                ? User::find((int) $opt)
                : User::where('email', $opt)->first();
            if ($user === null) {
                $this->warn("--author={$opt} に該当するユーザーが見つかりません。自動解決に切り替えます。");
            } else {
                return $user;
            }
        }

        return User::where('is_admin', true)->orderBy('id')->first()
            ?? User::orderBy('id')->first();
    }

    private function publishedAt(): Carbon
    {
        $date = trim((string) $this->option('date'));
        if ($date !== '') {
            return Carbon::parse($date);
        }

        return Carbon::now();
    }

    /**
     * 既存タグのみを sync（新規作成はしない）。存在しないタグは警告して skip。
     *
     * @return list<string> 実際に添付したタグ名
     */
    private function attachExistingTags(BlogPost $post): array
    {
        $found = BlogTag::whereIn('name', self::TAGS)->get();
        $missing = array_values(array_diff(self::TAGS, $found->pluck('name')->all()));

        if ($missing !== []) {
            $this->warn('存在しないタグは添付しませんでした（新規作成しません）: '.implode(' / ', $missing));
        }

        $post->tags()->sync($found->pluck('id')->all());

        return $found->pluck('name')->all();
    }

    private function body(): string
    {
        // ★数値は一次資料確定。編集しないこと（特に原付12ヶ月=7,730円）。H1はtitleが担うため本文に含めない。
        return <<<'MD'
2026年11月1日から、自賠責保険（自動車損害賠償責任保険）の保険料が改定されます。全車種平均では約6.2%の引き上げですが、**バイクはそれより大きく、原付は約12%上がります。**

この記事では、排気量別・契約期間別の新旧料金をすべて並べたうえで、10月31日までにできることを整理します。

---

## 結論を先に

- 適用されるのは **2026年11月1日以降に「保険期間が始まる」契約**
- 上がり幅は **原付が最大（約12%）**、軽二輪・小型二輪は約8〜10%
- **契約日ではなく、保険期間の開始日で決まります**
- 10月31日までに始まる契約なら現行料率。長期契約にすればその料率を長く固定できます

---

## いつから変わるのか

損害保険料率算出機構が2026年4月30日に金融庁長官へ届出を行い、5月21日に適合性審査が終了しました。新しい基準料率は、**2026年11月1日以降に保険期間の始期を有する保険契約**に適用されます。

ここが間違えやすいところです。**「いつ申し込んだか」ではなく「保険期間がいつ始まるか」で決まります。** 10月中に手続きをしても、保険期間の開始が11月1日以降であれば新料率です。


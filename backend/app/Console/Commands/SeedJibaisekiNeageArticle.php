## 10月31日までにできること

**保険期間の開始日が10月31日以前**であれば、現行料率が適用されます。そのうえで契約期間を長くとれば、値上げ後の料率をその期間だけ避けられます。

たとえば5年契約なら、差額はこうなります。

| 区分 | 60ヶ月契約の差額 |
|---|---|
| 原付（125cc以下） | **1,720円** |
| 軽二輪（125cc超〜250cc以下） | **1,170円** |

小型二輪（250cc超）は最長37ヶ月で、差額は1,030円です。

### ただし、当てはまる人は限られます

正直に書くと、この恩恵を受けられるのは次のどちらかです。

- **10月中にバイクを新規登録する人**
- **加入中の自賠責が10月中に満了し、そのまま更新する人**

契約が11月以降に満了する人が、それを待たずに入り直すのは得になりません。自賠責は解約に制限があり、途中で入り直しても前契約の残りが無駄になるためです。

**「値上げ前に駆け込みで入り直す」ではなく、「もともと10月に更新の人は長めに契約しておく」**という理解が正確です。

### 250cc以下の人は特に忘れやすい

250cc超は車検のたびに自賠責も一緒に更新するので、期限を意識せずに済みます。一方、**250cc以下は車検がないため、自分で期限を管理する必要があります。**

証明書の満了日を一度確認してみてください。10月中に切れるなら、長期契約を検討する価値があります。


## よくある質問

**Q. 10月中に申し込めば現行料率ですか？**

保険期間の開始日が10月31日以前であれば現行料率です。申込日ではなく開始日で判断されます。

**Q. 今入っている自賠責は値上がりしますか？**

いいえ。すでに始まっている契約の保険料が途中で変わることはありません。次の更新時から新料率が適用されます。

**Q. 離島や沖縄も同じ料金ですか？**

いいえ。離島および沖縄県は別の料率が設定されており、本土より安くなっています。この記事の表は本土（離島・沖縄を除く）の料率です。

**Q. 新基準原付はどの区分ですか？**

2025年の新基準原付（総排気量125cc以下で最高出力4.0kW以下に制御したもの）は原付一種として扱われ、自賠責も「一般原動機付自転車」の料率が適用されます。

**Q. 電動キックボードは？**

特定小型原動機付自転車は別区分で、改定後の12ヶ月は7,430円です。


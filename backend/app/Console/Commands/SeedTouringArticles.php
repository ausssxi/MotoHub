    protected $signature = 'blog:seed-touring-articles {--force : 同名記事が存在しても再作成する}';
    protected $description = 'ツーリングルート記事をブログに自動投稿します（4記事）';

    public function handle(): int
    {
        $articles = $this->getArticles();

        $tag = BlogTag::firstOrCreate(
            ['name' => 'ツーリング'],
            ['slug' => Str::slug('ツーリング') ?: Str::lower(Str::random(10))],
        );

        $created = 0;

        foreach ($articles as $article) {
            $exists = BlogPost::where('title', $article['title'])->exists();

            if ($exists && ! $this->option('force')) {
                $this->line("  スキップ（既存）: {$article['title']}");
                continue;
            }

            if ($exists) {
                BlogPost::where('title', $article['title'])->forceDelete();
                $this->warn("  削除（再作成）: {$article['title']}");
            }

            $post = BlogPost::create([
                'author_id' => 1,
                'title' => $article['title'],
                'body' => $article['body'],
                'status' => 'published',
                'published_at' => now(),
                'latitude' => $article['lat'],
                'longitude' => $article['lng'],
            ]);

            $post->tags()->sync([$tag->id]);

            $created++;
            $this->info("  作成: [{$post->id}] {$post->title}");
        }

        $this->info("完了: {$created} 記事を作成しました。");

        return self::SUCCESS;
    }


    /**
     * 住所の先頭市区名から都道府県を引く。該当しなければ null。
     */
    public static function fromCity(string $address): ?string
    {
        foreach (self::MAP as $city => $prefecture) {
            if (str_starts_with($address, $city)) {
                return $prefecture;
            }
        }

        return null;
    }

    /**
     * 住所が47都道府県のいずれかで始まるか。ジオコーディング時の都道府県二重前置防止に使う。
     */
    public static function startsWithPrefecture(string $address): bool
    {
        foreach (self::PREFECTURES as $prefecture) {
            if (str_starts_with($address, $prefecture)) {
                return true;
            }
        }

        return false;
    }

    /**
     * 住所の先頭市区名から都道府県を引く。該当しなければ null。
     */
    public static function fromCity(string $address): ?string
    {
        foreach (self::MAP as $city => $prefecture) {
            if (str_starts_with($address, $city)) {
                return $prefecture;
            }
        }

        return null;
    }

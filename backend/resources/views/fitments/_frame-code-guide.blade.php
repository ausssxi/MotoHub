        <i data-lucide="search" class="w-4 h-4 text-blue-600"></i> 型式（フレームコード）の調べ方
    </h2>
    <p class="text-sm text-gray-600 leading-relaxed">
        型式は車台番号（フレーム番号）の先頭部分です（例: 車台番号が <b>AF62-…</b> なら型式は <b>AF62</b>）。
        打刻位置は車種により異なるため、最も確実なのは
        <b>自賠責保険証明書・標識交付証明書・軽自動車届出済証</b>の「車台番号」欄の確認です。
